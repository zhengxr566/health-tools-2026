WHOLE_STAPLES = {"糙米饭", "燕麦片（干）", "红薯（蒸 / 烤）", "土豆（煮）", "甜玉米（玉米粒）"}

TW_MAP = {"修正熱量": "kcal", "粗蛋白": "protein", "粗脂肪": "fat", "總碳水化合物": "carbs", "膳食纖維": "fiber",
          "鈉": "sodium", "鉀": "potassium", "鈣": "calcium", "鐵": "iron", "鎂": "magnesium", "鋅": "zinc",
          "視網醇": "retinol", "β-胡蘿蔔素": "bcar", "α-胡蘿蔔素": "acar", "維生素C": "vit_c",
          "維生素D總量(ug)": "vit_d"}
US_MAP = {"1008": "kcal", "1003": "protein", "1004": "fat", "1005": "carbs", "1079": "fiber", "1093": "sodium",
          "1092": "potassium", "1087": "calcium", "1089": "iron", "1090": "magnesium", "1095": "zinc",
          "1106": "vit_a", "1162": "vit_c", "1114": "vit_d"}

tw_need = {c for _, _, _, s, c, _ in FOODS if s == "TW"}
us_need = {c for _, _, _, s, c, _ in FOODS if s == "US"}

tw = {}
with open(TW_CSV, encoding="utf-8-sig", newline="") as f:
    for row in csv.DictReader(f):
        code = row["整合編號"]
        if code not in tw_need:
            continue
        d = tw.setdefault(code, {"_name": row["樣品名稱"]})
        k = TW_MAP.get(row["分析項"])
        if k:
            v = row["每100克含量"].strip()
            d[k] = float(v) if v not in ("", "-") else None
for code, d in tw.items():
    parts = [d.get("retinol"), d.get("bcar"), d.get("acar")]
    d["vit_a"] = None if all(p is None for p in parts) else (
        (d.get("retinol") or 0) + (d.get("bcar") or 0) / 12 + (d.get("acar") or 0) / 24)

us = {c: {} for c in us_need}
us_names = {}
with open(f"{US_DIR}/food.csv", encoding="utf-8", newline="") as f:
    for row in csv.DictReader(f):
        if row["fdc_id"] in us_need:
            us_names[row["fdc_id"]] = row["description"]
with open(f"{US_DIR}/food_nutrient.csv", encoding="utf-8", newline="") as f:
    for row in csv.DictReader(f):
        if row["fdc_id"] in us_need and row["nutrient_id"] in US_MAP:
            us[row["fdc_id"]][US_MAP[row["nutrient_id"]]] = float(row["amount"])

out, missing_report = [], []
for i, (grp, name, alias, src, code, units) in enumerate(FOODS):
    d = tw.get(code) if src == "TW" else us.get(code)
    if not d or (src == "US" and code not in us_names):
        raise SystemExit(f"missing food {src} {code} {name}")
    vals, missing = [], []
    for k in KEYS:
        v = d.get(k)
        if v is None:
            missing.append(k)
            v = 0.0
        vals.append(round(v, 2 if k in ("iron", "zinc", "vit_d") else 1))
    if missing:
        missing_report.append(f"{name}: {','.join(missing)}")
    # r=1：适合作为“怎么补”推荐的天然食物（排除加工主食、调味料、饮料零食和油）
    rec = grp in ("蛋奶豆", "肉鱼", "蔬菜", "水果") or name in WHOLE_STAPLES or (grp == "坚果油脂" and "油" not in name)
    if name in ("培根（煎）", "火腿片", "奶酪片", "豆浆（含糖）", "酸奶（含糖）"):
        rec = False
    out.append({"id": i + 1, "n": name, "g": grp, "a": alias, "src": src, "ref": code, "r": 1 if rec else 0,
                "u": [[u, g] for u, g in units], "v": vals,
                "orig": d.get("_name") if src == "TW" else us_names[code]})

Path(OUT).parent.mkdir(parents=True, exist_ok=True)
json.dump({"keys": KEYS, "foods": out}, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
print("foods:", len(out), "bytes:", Path(OUT).stat().st_size)
print("missing values (treated as 0):")
for m in missing_report:
    print("  ", m)
for f in out:
    v = dict(zip(KEYS, f["v"]))
    print(f"{f['n']:<16} {f['src']} {f['orig'][:38]:<38} kcal {v['kcal']:>6} P {v['protein']:>5} Ca {v['calcium']:>6} Fe {v['iron']:>5} VA {v['vit_a']:>6} VC {v['vit_c']:>5} Na {v['sodium']:>7}")
